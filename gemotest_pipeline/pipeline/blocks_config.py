def get_blocks_by_pass(pass_group: int) -> list[dict]:
    """Return all block definitions assigned to a given pass group."""
    return [b for b in BLOCKS.values() if b["pass_group"] == pass_group]


def get_blocks_by_section(section: str) -> list[dict]:
    """Return blocks for a given section ('b2c', 'b2b', 'geo', 'platform')."""
    return [b for b in BLOCKS.values() if b["section"] == section]


